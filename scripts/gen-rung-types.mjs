#!/usr/bin/env node
/**
 * gen-rung-types.mjs — emit rungs.generated.ts from rungs.json.
 *
 * rungs.json is the source of truth, not this output. JSON rather than a TS module because
 * the manifest has TWO consumers in TWO languages: the TS shell reads it for routing, and
 * `pnpm eject` must edit apps/{django,fastapi}-backend/**\/ai_backends/ — a Python plane that
 * pnpm cannot even see (neither backend has a package.json, so despite the `apps/*` workspace
 * glob they are absent from the lockfile). A TS module would be unreadable to that half.
 *
 * The emitted types give the shell's routing switch exhaustiveness at compile time: add a
 * sixth rung or a third shape to rungs.json without adding a branch, and tsc fails.
 *
 * CI re-runs this and fails if the output differs from what is committed, so the generated
 * file can never drift from the manifest.
 *
 * Usage:  node scripts/gen-rung-types.mjs [--check]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

// TREE is the repo being generated FOR; ROOT is where this script lives. They differ whenever
// eject runs with --cwd, and conflating them was a defect that could not fail: the generator
// regenerated the SOURCE repo's types and never touched the fork's, so a fork's rungs.json said
// one rung while its generated.ts still declared all five. A manifest-driven UI validated
// through --cwd would render five rungs in a one-rung fork and look correct.
//
// The check passed because its subject was the source repo, which is right by construction.
// RUNGS_CWD mirrors classify.mjs, which already had this precedent.
const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TREE = process.env.RUNGS_CWD || ROOT;
const OUT = join(TREE, "packages", "rungs", "src", "generated.ts");
const manifest = JSON.parse(
  readFileSync(process.env.RUNGS_MANIFEST || join(TREE, "rungs.json"), "utf8")
);

const q = (s) => JSON.stringify(s);
const union = (xs) => (xs.length ? xs.map(q).join(" | ") : "never");

const rungIds = manifest.rungs.map((r) => r.id);
const shapes = manifest.shapes;
const states = Object.keys(manifest.states);

const body = `// GENERATED BY scripts/gen-rung-types.mjs FROM rungs.json — DO NOT EDIT.
// Run \`node scripts/gen-rung-types.mjs\` after changing rungs.json. CI fails if this drifts.
//
// rungs.json is the single authority on what a rung is. These types exist so the shape-routed
// shell's routing switch is exhaustive at COMPILE time: add a rung or a shape to the manifest
// without adding a branch and tsc fails, instead of a rung silently rendering nothing.

/** Every rung in the ladder, in ordinal order. */
export type RungId = ${union(rungIds)};

/**
 * Interaction shape. #23 ruled this is a declared rung property and the shell routes by it.
 *
 * NOTE: a shape is NOT a stream topology. \`run\` does not mean "one run". Real Open SWE
 * registers three graphs (manager/planner/programmer) that do not share a run, so anything
 * describing threads, runs, or endpoints belongs in the shape handler, never here.
 * See apps/open-swe/docs/LOCAL-AGENT.md, "Topology: this backend is single-run".
 */
export type RungShape = ${union(shapes)};

/** Availability. \`planned\` rungs have no files and no target — render them without a link. */
export type RungState = ${union(states)};

/**
 * Where the shell sends you for a rung. Deliberately a discriminated union: "one rung = one
 * route" cannot express the ladder as it actually exists. Rungs 1-3 share ONE surface and are
 * selected by a param; rung 4 is a whole app on a DIFFERENT ORIGIN; rung 5 has no target.
 */
export type RungTarget =
  | { readonly kind: "param"; readonly app: string; readonly route: string; readonly param: string; readonly value: string }
  | { readonly kind: "origin"; readonly app: string; readonly originEnv: string; readonly originFallback: string; readonly route: string }
  | { readonly kind: "none" };
// There is deliberately no "route" variant. No rung has its own in-app route, and a variant
// nothing exercises cannot be tested, rots, and reads to a reviewer as "handled" when nothing
// proved it. Adding one later is a schema line plus a compile error from assertNever() pointing
// at the exact switch that needs a branch — the compiler tells the next person where to go.

export type RuntimeId = string;

export interface RungRuntime {
  /**
   * Topologies this (rung, runtime) pair serves.
   *
   * AN EMPTY ARRAY MEANS ONE CELL WITH NO TOPOLOGY AXIS — NOT ZERO CELLS. Prefer matrixCells()
   * over reading this directly; that rule is encoded once, there, deliberately.
   */
  readonly topologies: readonly string[];
  readonly topologiesSource?: string;
}

export interface Rung {
  readonly id: RungId;
  readonly ordinal: number;
  readonly shape: RungShape;
  readonly state: RungState;
  readonly requires: readonly RungId[];
  /** Language planes owning files for this rung — drives the 8-job severability matrix. */
  readonly languages: readonly ("ts" | "py")[];
  /**
   * Which backends SERVE this rung, and what each offers.
   *
   * NOT the same as languages, which is which planes hold files this rung OWNS. Rung 1 has
   * languages [ts, py] — it owns a TS adapter and two Python modules — but runtimes
   * [django, fastapi], because no node runtime serves it. Close enough to be conflated,
   * different enough that conflating them would be wrong.
   */
  readonly runtimes: Readonly<Record<RuntimeId, RungRuntime>>;
  readonly target: RungTarget;
}

/** One cell of the behavioural matrix: a (rung, runtime, topology?) triple. */
export interface MatrixCell {
  readonly rung: RungId;
  readonly runtime: RuntimeId;
  /** undefined when the pair has no topology axis — every run-shaped rung. */
  readonly topology?: string;
  readonly shape: RungShape;
  readonly state: RungState;
}

export const RUNG_IDS = [${rungIds.map(q).join(", ")}] as const;
export const RUNG_SHAPES = [${shapes.map(q).join(", ")}] as const;

export const RUNGS: readonly Rung[] = [
${manifest.rungs
  .map(
    (r) => `  {
    id: ${q(r.id)},
    ordinal: ${r.ordinal},
    shape: ${q(r.shape)},
    state: ${q(r.state)},
    requires: [${r.requires.map(q).join(", ")}],
    languages: [${r.languages.map(q).join(", ")}],
    runtimes: ${JSON.stringify(r.runtimes)},
    target: ${JSON.stringify(r.target)},
  },`
  )
  .join("\n")}
] as const;

/** Lookup by id. Total over RungId, so callers need no undefined check. */
export const RUNG_BY_ID: Readonly<Record<RungId, Rung>> = Object.fromEntries(
  RUNGS.map((r) => [r.id, r])
) as Readonly<Record<RungId, Rung>>;

/**
 * Rungs a fork retains when ejected to \`target\` — the transitive closure of \`requires\`,
 * lowest ordinal first. Each rung is a superset of the concerns below it, so ejecting never
 * leaves a bare single rung.
 */
export function retainedRungs(target: RungId): readonly Rung[] {
  const keep = new Set<RungId>();
  const visit = (id: RungId) => {
    if (keep.has(id)) return;
    keep.add(id);
    RUNG_BY_ID[id].requires.forEach(visit);
  };
  visit(target);
  return RUNGS.filter((r) => keep.has(r.id));
}

/**
 * Every cell of the behavioural matrix.
 *
 * THE ONE PLACE THE EMPTY-TOPOLOGIES RULE LIVES. An empty topologies array means one cell with
 * no topology axis, not zero cells — a run-shaped rung still has to be exercised. Three
 * consumers derive matrix arity from this manifest, and a semantic that can be guessed wrong
 * should be a function rather than a comment, so that none of them re-derives it.
 *
 * The ladder is ragged: deep-research exists only in deepagents x fastapi. A uniform
 * 3 x 2 x 3 grid emits 20 cells, five of which do not exist. This emits 15.
 *
 * Callers wanting only runnable cells should filter on state — a planned rung has no
 * implementation to exercise.
 */
export function matrixCells(): readonly MatrixCell[] {
  const out: MatrixCell[] = [];
  for (const rung of RUNGS) {
    for (const [runtime, cfg] of Object.entries(rung.runtimes)) {
      if (cfg.topologies.length === 0) {
        out.push({ rung: rung.id, runtime, shape: rung.shape, state: rung.state });
      } else {
        for (const topology of cfg.topologies) {
          out.push({ rung: rung.id, runtime, topology, shape: rung.shape, state: rung.state });
        }
      }
    }
  }
  return out;
}

/**
 * Resolve a rung's URL. The substitution rule, in one place: the literal [param] in
 * target.route is replaced by target.value.
 *
 * Returns null when there is nothing to link to — a planned rung — so callers render it as
 * declared-but-absent rather than offering a dead link.
 */
export function rungHref(rung: Rung, env: Record<string, string | undefined> = {}): string | null {
  const t = rung.target;
  if (t.kind === "none") return null;
  if (t.kind === "param") return t.route.replace(\`[\${t.param}]\`, t.value);
  return \`\${env[t.originEnv] ?? t.originFallback}\${t.route}\`;
}

/** Exhaustiveness helper: \`default: return assertNever(shape)\` fails to compile on a new shape. */
export function assertNever(x: never): never {
  throw new Error(\`Unhandled rung variant: \${JSON.stringify(x)}\`);
}
`;

if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(OUT, "utf8");
  } catch {
    console.error(
      "FAIL: rungs.generated.ts is missing. Run: node scripts/gen-rung-types.mjs"
    );
    process.exit(1);
  }
  if (current !== body) {
    console.error(
      "FAIL: packages/rungs/src/generated.ts is stale — it does not match rungs.json.\n" +
        "      Run: node scripts/gen-rung-types.mjs"
    );
    process.exit(1);
  }
  console.log("PASS: rungs.generated.ts matches rungs.json");
} else {
  writeFileSync(OUT, body);
  console.log(
    `wrote ${OUT} (${manifest.rungs.length} rungs, ${shapes.length} shapes)`
  );
}
