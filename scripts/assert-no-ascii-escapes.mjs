/**
 * `scripts/checks.json` SPELLS ITS CHARACTERS LITERALLY (#828).
 *
 * A JSON serializer run with `ensure_ascii=True` rewrites every non-ASCII character as a
 * `\uXXXX` escape. The file still parses to the identical object, so the change is invisible to
 * every check we own — and it reached main on 2026-09-05 in #821, rewriting 29 literal em-dashes
 * as 41 escape occurrences across 30 lines, and making those lines of other people's prose
 * conflict for four branches at once. The two counts are both right and measure different
 * things: `grep -c` counts LINES CONTAINING, and some lines carry more than one escape. A
 * restoration verified by the line count would read as complete while leaving a second escape
 * on a line it had already counted.
 *
 * WHY A BYTE CHECK HAS TO EXIST RATHER THAN BEING A NICETY. Three instruments already read this
 * file and NONE of them can see this class — not by oversight, but BY CONSTRUCTION, for any
 * input, ever:
 *
 *   - set containment compares NAMES. A serializer can rewrite every byte of every `why` and
 *     `reason` in the file and the comparison still reads ADDED [] LOST [].
 *   - prettier's subject is SYNTAX. Both spellings are well-formed JSON, so both are already
 *     formatted and it has nothing to say.
 *   - a PARSED diff normalises the two spellings to one string before comparing, so the
 *     difference is gone before the comparison starts.
 *
 * Each passes because the property it examines genuinely does not vary. That is why the guard
 * has to read BYTES: it is the only subject on which the two spellings differ at all.
 *
 * IT ASSERTS OVER THE ESCAPE CLASS, NOT OVER THE ONE CHARACTER WE HIT. main's checks.json
 * carried 41 escape occurrences and all 41 happened to be em-dashes, so an em-dash-only
 * restoration was complete THERE and would have silently left curly quotes, en-dashes and
 * non-breaking spaces behind on the next file. This refuses any `\uXXXX` whose character has a
 * literal form, so the next serializer run is caught whatever it rewrites.
 *
 * WHAT IT DOES NOT COVER, said here because #824's header had to be corrected for exactly this.
 * Its subject is `scripts/checks.json` and nothing else. `scripts/eject-subject-census.json` is
 * the same extension and would be the obvious thing to add, and it must not be added: the census
 * is REGENERATED by `pnpm eject-audit`, so its repair is "re-run the producer", while this file
 * is hand-written and its repair is "edit the bytes". Same defect, opposite correct repair, and
 * one verdict must not span both. That is #811's question and it is tracked as #834/#835.
 *
 * Exit 0 every character that can be literal is literal · 1 at least one is escaped.
 */
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";
import { invokedAsProgram } from "./lib/is-main.mjs";
import { reportSubject } from "./lib/subject.mjs";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/**
 * JSON REQUIRES these to be escaped, so an escape here is correct rather than a defect:
 * the control range, the quote, and the backslash. Everything else has a literal form.
 * DEL is included because it is a control character with no useful literal spelling.
 */
export const mustBeEscaped = (cp) =>
  cp < 0x20 || cp === 0x22 || cp === 0x5c || cp === 0x7f;

/**
 * Every `\uXXXX` escape actually inside a JSON string, with its line.
 *
 * This walks the raw text tracking string context and escape state rather than grepping,
 * because a grep for `\\u` cannot tell an escape from an escaped BACKSLASH followed by the
 * letter u: in `"a\\\\u2014b"` the characters `u2014` are literal text, not an escape. Consuming
 * `\\` as a pair is what separates the two, and a regex over the whole file cannot.
 */
export function escapesIn(raw) {
  const found = [];
  let inString = false;
  let strings = 0;
  let line = 1;
  let i = 0;
  while (i < raw.length) {
    const ch = raw[i];
    if (ch === "\n") {
      line++;
      i++;
      continue;
    }
    if (!inString) {
      if (ch === '"') inString = true;
      i++;
      continue;
    }
    if (ch === "\\") {
      if (raw[i + 1] === "u") {
        const hex = raw.slice(i + 2, i + 6);
        found.push({ line, hex, cp: Number.parseInt(hex, 16) });
        i += 6;
        continue;
      }
      i += 2; // any other escape, INCLUDING \\, consumes both characters
      continue;
    }
    if (ch === '"') {
      inString = false;
      strings++;
      i++;
      continue;
    }
    i++;
  }
  return { found, strings };
}

/** Which of those escapes name a character that has a literal form. */
export function escapeComplaints(found) {
  return found
    .filter((e) => !mustBeEscaped(e.cp))
    .map(
      (e) =>
        `line ${e.line}: \\u${e.hex} is "${String.fromCodePoint(
          e.cp
        )}", which has a literal form`
    );
}

function main() {
  const raw = readFileSync(join(ROOT, "scripts/checks.json"), "utf8");
  const { found, strings } = escapesIn(raw);
  const bad = escapeComplaints(found);

  if (bad.length > 0) {
    console.error(
      `FAIL: scripts/checks.json has ${bad.length} escaped character(s) that have a literal form:`
    );
    for (const b of bad.slice(0, 20)) console.error(`  - ${b}`);
    if (bad.length > 20) console.error(`  ... and ${bad.length - 20} more.`);
    console.error(
      `\n      This is what a JSON serializer run with ensure_ascii=True produces. The file\n` +
        `      still parses to the same object, so name comparison, prettier and any parsed\n` +
        `      diff all pass — none of them reads bytes. Rewrite the escapes as the literal\n` +
        `      characters; do not "fix" it by re-serialising, which is what caused it.`
    );
    process.exit(1);
  }

  reportSubject(
    strings,
    "string(s) in `scripts/checks.json` read byte by byte"
  );
  console.log(
    `PASS: every character in scripts/checks.json that has a literal form is written` +
      ` literally.\n` +
      `      ${found.length} escape(s) present, all of them required by JSON itself.`
  );
}

if (invokedAsProgram(import.meta.url)) main();
